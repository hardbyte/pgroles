function appendStatementResults(target, statementResults) {
  for (const result of statementResults) {
    if (result.command) target.commands.push(result.command)
    if (result.fields?.length > 0) {
      target.results.push({
        fields: result.fields.map((field) => field.name),
        rows: result.rows,
      })
    }
  }
}

async function executeStatements(database, statements) {
  const output = { commands: [], results: [], entries: [], error: null }
  let activeActor = null

  for (let index = 0; index < statements.length; index += 1) {
    const statement = statements[index]
    const sql = statementSql(statement)
    const actor = typeof statement === 'string' ? null : statement.actor
    const entry = {
      sql,
      actor,
      commands: [],
      results: [],
      error: null,
    }
    output.entries.push(entry)

    try {
      if (actor && actor !== activeActor) {
        await database.exec('RESET ROLE;')
        await database.exec(
          `SET SESSION AUTHORIZATION "${actor.replaceAll('"', '""')}";`
        )
        activeActor = actor
      }

      const statementResults = await database.exec(`${sql};`)
      appendStatementResults(output, statementResults)
      appendStatementResults(entry, statementResults)
    } catch (error) {
      output.error = error.message
      output.errorCode = error.code
      output.errorIndex = index
      entry.error = error.message
      entry.errorCode = error.code
      break
    }
  }

  try {
    await database.exec('RESET ROLE;')
    await database.exec('SET SESSION AUTHORIZATION postgres;')
  } catch {
    // Guided SQL never receives superuser access, so this only guards teardown.
  }

  return output
}

async function executeSetupStatements(database, statements) {
  const output = { commands: [], results: [], error: null }

  for (let index = 0; index < statements.length; index += 1) {
    try {
      const statementResults = await database.exec(`${statements[index]};`)
      appendStatementResults(output, statementResults)
    } catch (error) {
      output.error = error.message
      output.errorCode = error.code
      output.errorIndex = index
      break
    }
  }

  return output
}

function normalizeSql(sql) {
  return sql
    .trim()
    .replace(/;+\s*$/, '')
    .replace(/\s+/g, ' ')
    .toLowerCase()
}

