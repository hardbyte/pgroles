function SqlTokens({ code }) {
  return (
    <Highlight {...defaultProps} code={code} language="sql" theme={undefined}>
      {({ tokens, getTokenProps }) =>
        tokens.map((line, lineIndex) => (
          <Fragment key={lineIndex}>
            <span>
              {line
                .filter((token) => !token.empty)
                .map((token, tokenIndex) => (
                  <span key={tokenIndex} {...getTokenProps({ token })} />
                ))}
            </span>
            {lineIndex < tokens.length - 1 ? '\n' : null}
          </Fragment>
        ))
      }
    </Highlight>
  )
}

function statementSql(statement) {
  return typeof statement === 'string' ? statement : statement.sql
}

function SqlSource({
  statements,
  highlightStatements = [],
  label = 'SQL for this step',
  maxHeight = 'max-h-[24rem]',
}) {
  let nextLine = 1

  return (
    <pre
      aria-label={label}
      className={`language-sql m-0 ${maxHeight} overflow-auto rounded-none bg-[#0c0e12] py-4 text-xs leading-5`}
    >
      <code>
        {statements.map((statement, statementIndex) => {
          const sql = statementSql(statement)
          const code = `${sql};`
          const startLine = nextLine
          nextLine += code.split('\n').length
          const highlighted = highlightStatements.includes(statementIndex)

          return (
            <Highlight
              key={`${statementIndex}-${sql}`}
              {...defaultProps}
              code={code}
              language="sql"
              theme={undefined}
            >
              {({ tokens, getTokenProps }) => (
                <span
                  className={`block border-l-2 py-0.5 ${
                    highlighted
                      ? 'border-amber-400 bg-amber-300/10'
                      : 'border-transparent'
                  }`}
                >
                  {tokens.map((line, lineIndex) => (
                    <Fragment key={lineIndex}>
                      <span className="grid grid-cols-[2.75rem_1fr] px-3 sm:px-4">
                        <span
                          aria-hidden="true"
                          className={`select-none pr-3 text-right font-mono ${
                            highlighted ? 'text-amber-400' : 'text-stone-600'
                          }`}
                        >
                          {startLine + lineIndex}
                        </span>
                        <span className="min-w-0 whitespace-pre-wrap break-words">
                          {line
                            .filter((token) => !token.empty)
                            .map((token, tokenIndex) => (
                              <span
                                key={tokenIndex}
                                {...getTokenProps({ token })}
                              />
                            ))}
                        </span>
                      </span>
                      {lineIndex === tokens.length - 1 && (
                        <span className="block h-3" />
                      )}
                    </Fragment>
                  ))}
                </span>
              )}
            </Highlight>
          )
        })}
      </code>
    </pre>
  )
}

function SqlEditor({
  value,
  onChange,
  disabled,
  ariaLabel = 'SQL playground',
  minHeight = 'min-h-[11rem]',
}) {
  const highlightRef = useRef(null)

  function syncScroll(event) {
    if (!highlightRef.current) return
    highlightRef.current.scrollTop = event.currentTarget.scrollTop
    highlightRef.current.scrollLeft = event.currentTarget.scrollLeft
  }

  return (
    <div
      className={`relative ${minHeight} overflow-hidden rounded-xl border border-stone-700 bg-[#0c0e12] focus-within:border-amber-400 focus-within:ring-2 focus-within:ring-amber-400/20`}
    >
      <pre
        ref={highlightRef}
        aria-hidden="true"
        className={`pointer-events-none absolute inset-0 m-0 ${minHeight} overflow-hidden whitespace-pre p-4 font-mono text-xs leading-6 text-stone-200`}
      >
        <code>
          <SqlTokens code={value || ' '} />
        </code>
      </pre>
      <textarea
        aria-label={ariaLabel}
        value={value}
        onChange={(event) => onChange(event.target.value)}
        onScroll={syncScroll}
        disabled={disabled}
        wrap="off"
        spellCheck="false"
        className={`relative z-10 m-0 ${minHeight} w-full resize-y overflow-auto border-0 bg-transparent p-4 font-mono text-xs leading-6 text-transparent outline-none selection:bg-amber-300/30 disabled:cursor-wait`}
        style={{ caretColor: '#f5f5f4', WebkitTextFillColor: 'transparent' }}
      />
    </div>
  )
}

function valueText(value) {
  if (value === null) return 'NULL'
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  return String(value)
}

function resultsMatchExpectations(results, expectations = []) {
  return expectations.every((expectation) => {
    const result = results[expectation.index]
    if (!result) return false
    if (
      expectation.rowCount !== undefined &&
      result.rows.length !== expectation.rowCount
    )
      return false
    if (!expectation.rows) return true
    if (result.rows.length !== expectation.rows.length) return false

    return expectation.rows.every((expectedRow, rowIndex) =>
      Object.entries(expectedRow).every(
        ([field, value]) => result.rows[rowIndex]?.[field] === value
      )
    )
  })
}

