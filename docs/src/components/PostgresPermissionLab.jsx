function SqlOutput({
  output,
  operation,
  kind = 'lesson',
  expectedError = false,
}) {
  const runningThisOutput =
    operation === kind || operation === 'booting' || operation === 'preparing'

  if (operation === 'booting') {
    return (
      <p className="m-0 text-sm text-stone-300">
        Downloading and starting PostgreSQL 18.3…
      </p>
    )
  }
  if (operation === 'preparing') {
    return (
      <p className="m-0 text-sm text-stone-300">
        Preparing this lesson’s roles and objects…
      </p>
    )
  }
  if (runningThisOutput) {
    return <p className="m-0 text-sm text-stone-300">Executing SQL…</p>
  }
  if (!output) {
    return (
      <p className="m-0 text-sm leading-6 text-stone-400">
        PostgreSQL’s command tags, rows, and exact error will appear here.
      </p>
    )
  }

  return (
    <div className="space-y-4">
      {output.commands.length > 0 && (
        <div
          className="flex flex-wrap gap-1.5"
          aria-label="PostgreSQL command results"
        >
          {output.commands.map((command, index) => (
            <span
              key={`${command}-${index}`}
              className="rounded-md border border-stone-700 bg-stone-800 px-2 py-1 font-mono text-[10px] text-stone-300"
            >
              {command}
            </span>
          ))}
        </div>
      )}
      {output.results.map((entry, index) => (
        <ResultTable key={index} entry={entry} />
      ))}
      {output.error && (
        <div
          className={`rounded-xl border px-4 py-3 font-mono text-xs ${
            expectedError
              ? 'border-amber-700/70 bg-amber-950/35 text-amber-200'
              : 'border-red-800 bg-red-950/40 text-red-200'
          }`}
        >
          <span className="font-semibold">ERROR:</span> {output.error}
        </div>
      )}
      {kind !== 'lesson' && !output.error ? (
        <p className="m-0 text-sm font-semibold text-emerald-300">
          ✓ SQL completed
        </p>
      ) : null}
    </div>
  )
}

